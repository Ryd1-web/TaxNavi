namespace TaxNavi.Infrastructure.Services;

using TaxNavi.Domain.Entities;
using TaxNavi.Domain.Interfaces;
using System.Text;
using QuestPDF.Fluent;
using QuestPDF.Infrastructure;
using QuestPDF.Helpers;
using Microsoft.Extensions.Logging;

public class PdfReportService : IPdfService
{
    private readonly IBlobStorageService _blobStorageService;
    private readonly ILogger<PdfReportService> _logger;

    public PdfReportService(IBlobStorageService blobStorageService, ILogger<PdfReportService> logger)
    {
        _blobStorageService = blobStorageService;
        _logger = logger;
        QuestPDF.Settings.License = LicenseType.Community;
    }

    public async Task<byte[]> GenerateTaxReportPdfAsync(TaxReport report, string summary, string advice, string userName = "Taxpayer")
    {
        try
        {
            _logger.LogInformation("Starting PDF generation for report: {ReportId}", report.Id);

            // Generate actual PDF using QuestPDF
            var pdfBytes = Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(2, Unit.Centimetre);

                    page.Header().AlignCenter().Text("TAX NAVI.AI - TAX REPORT")
                        .FontSize(20)
                        .Bold();

                    page.Content().Column(column =>
                    {
                        column.Spacing(10);

                        // Report Header with taxpayer name
                        column.Item().Text($"Taxpayer: {userName}").FontSize(12).Bold();
                        column.Item().Text($"Date Generated: {report.CreatedAt:MMMM dd, yyyy}").FontSize(10);

                        column.Item().LineHorizontal(1);

                        // Tax Summary Section
                        column.Item().Text("TAX ASSESSMENT SUMMARY").Bold().FontSize(12);
                        column.Item().Table(table =>
                        {
                            table.ColumnsDefinition(columns =>
                            {
                                columns.RelativeColumn();
                                columns.RelativeColumn();
                            });

                            table.Cell().Text("Total Income").Bold();
                            table.Cell().AlignRight().Text($"₦{report.TotalIncome:N0}");

                            table.Cell().Text("Allowable Deductions").Bold();
                            table.Cell().AlignRight().Text($"₦{report.AllowableDeductions:N0}");

                            table.Cell().Text("Tax Liability").Bold();
                            table.Cell().AlignRight().Text($"₦{report.TaxLiability:N0}");

                            table.Cell().Text("Projected Savings").Bold();
                            table.Cell().AlignRight().Text($"₦{report.ProjectedSavings:N0}");
                        });

                        column.Item().LineHorizontal(1);

                        // AI Summary Section
                        column.Item().Text("AI-GENERATED SUMMARY").Bold().FontSize(12);
                        column.Item().Text(summary).FontSize(10);

                        column.Item().LineHorizontal(1);

                        // Recommendations Section
                        column.Item().Text("TAX OPTIMIZATION RECOMMENDATIONS").Bold().FontSize(12);
                        column.Item().Text(advice).FontSize(10);

                        column.Item().LineHorizontal(1);

                        // Footer
                        column.Item().AlignCenter().Text("This report is for informational purposes only. Please consult with a qualified tax professional.")
                            .FontSize(8)
                            .Italic();
                    });

                    page.Footer().AlignCenter().Text($"Generated by TaxNavi.ai | Page 1")
                        .FontSize(8);
                });
            }).GeneratePdf();

            _logger.LogInformation("PDF generation completed. Size: {Size} bytes, First bytes: {Bytes}",
                pdfBytes.Length,
                System.BitConverter.ToString(pdfBytes.Take(4).ToArray()));

            var fileName = $"tax-report-{report.Id}.pdf";
            await _blobStorageService.UploadFileAsync(pdfBytes, fileName);

            _logger.LogInformation("PDF saved to blob storage: {FileName}", fileName);

            return pdfBytes;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error generating PDF for report: {ReportId}", report.Id);
            throw;
        }
    }

    public async Task<string> UploadPdfToBlobStorageAsync(byte[] pdfContent, string fileName)
    {
        return await _blobStorageService.UploadFileAsync(pdfContent, fileName);
    }
}

public class PaymentService : IPaymentService
{
    private readonly string? _paystackSecretKey;

    public PaymentService()
    {
        _paystackSecretKey = Environment.GetEnvironmentVariable("PAYSTACK_SECRET_KEY");
    }

    public async Task<PaymentInitiationResponse> InitiatePaymentAsync(PaymentRequest request)
    {
        // Mock Paystack integration
        // In production, use actual Paystack API
        var reference = $"PAY-{DateTime.UtcNow.Ticks}";

        var response = new PaymentInitiationResponse
        {
            Reference = reference,
            AccessCode = GenerateAccessCode(),
            AuthorizationUrl = $"https://checkout.paystack.com/mock/{reference}"
        };

        return await Task.FromResult(response);
    }

    public async Task<PaymentVerificationResponse> VerifyPaymentAsync(string reference)
    {
        // Mock Paystack verification
        // In production, call actual Paystack API
        var response = new PaymentVerificationResponse
        {
            Success = true,
            Status = "success",
            Reference = reference
        };

        return await Task.FromResult(response);
    }

    private string GenerateAccessCode()
    {
        return Guid.NewGuid().ToString("N")[..12].ToUpper();
    }
}
